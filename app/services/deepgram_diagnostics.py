"""Content-free, bounded diagnostics for the live Deepgram relay."""

from __future__ import annotations

import json
import logging
import logging.handlers
import os
import stat
import sys
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


LOGGER_NAME = "openscribe.deepgram_live"
MAX_BYTES = 5 * 1024 * 1024
BACKUP_COUNT = 2
_LOGGER = logging.getLogger(LOGGER_NAME)
_CONFIG_LOCK = threading.Lock()
_WARNING_LOCK = threading.Lock()
_WARNING_EMITTED = False
_FILE_HANDLER: logging.Handler | None = None
_FILE_PATH: str | None = None
_STDOUT_HANDLER: logging.Handler | None = None

_EVENTS = frozenset({
    "phase", "recording_started", "provider_connect", "media_dispatch", "checkpoint",
    "provider_drain", "window_commit", "browser_ack", "recovery", "recording_finished",
    "recording_failed", "provider_close",
})
_FIELDS = frozenset({
    "diagnostic_id", "phase", "outcome", "failure", "provider_category", "close_class",
    "duration_ms", "window_no", "media_batches", "media_samples", "provider_results",
    "interim_results", "final_results", "metadata_events", "keepalives", "reconnects",
    "recovery_available", "unresolved", "exceptional_fallback", "last_completed_stage",
})
_ENUMS = {
    "phase": frozenset({"origin_check", "owner_check", "handshake", "preflight", "session_start", "connect", "authorize", "media_send", "provider_receive", "record_sent", "heartbeat", "keepalive", "browser_receive", "checkpoint", "finalize", "drain", "commit", "browser_ack", "recovery", "stop", "close", "recording"}),
    "outcome": frozenset({"started", "success", "failed", "timeout", "pending", "completed", "disconnected", "cancelled", "reconciled", "available", "unavailable", "none"}),
    "failure": frozenset({"stream_failed", "stream_provider_failed", "stream_transport_failed", "stream_protocol_invalid", "stream_session_expired", "stream_quota_exceeded", "stream_finalization_timeout", "stream_commit_failed", "stream_accounting_failed", "stream_lease_failed", "reconciliation_pending", "browser_ack_failed", "provider_close_failed"}),
    "provider_category": frozenset({"authentication_error", "connection_error", "invalid_config", "invalid_response", "provider_error", "provider_server_error", "rate_limit_exceeded", "timeout", "none"}),
    "close_class": frozenset({"normal", "going_away", "protocol_error", "unsupported_data", "abnormal", "policy_violation", "internal_error", "service_restart", "try_again_later", "unknown", "none"}),
    "last_completed_stage": frozenset({"session_started", "provider_connected", "media_dispatched", "finalized", "provider_drained", "window_committed", "browser_acknowledged", "reconciled", "none"}),
}
_COUNTERS = frozenset({"duration_ms", "window_no", "media_batches", "media_samples", "provider_results", "interim_results", "final_results", "metadata_events", "keepalives", "reconnects"})
_BOOLS = frozenset({"recovery_available", "unresolved", "exceptional_fallback"})


def _safe_record(event: str, diagnostic_id: str | None, fields: dict[str, Any]) -> dict[str, Any] | None:
    if not isinstance(event, str) or event not in _EVENTS or set(fields) - (_FIELDS - {"diagnostic_id"}):
        return None
    record: dict[str, Any] = {
        "event": event,
        "timestamp": datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z"),
    }
    if diagnostic_id is not None:
        # UUID hex IDs are generated by the relay. Do not accept arbitrary strings.
        if not isinstance(diagnostic_id, str) or len(diagnostic_id) != 32 or any(c not in "0123456789abcdef" for c in diagnostic_id):
            return None
        record["diagnostic_id"] = diagnostic_id
    for key, value in fields.items():
        if key in _ENUMS:
            if not isinstance(value, str) or value not in _ENUMS[key]:
                return None
        elif key in _COUNTERS:
            if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= 2**53 - 1:
                return None
        elif key in _BOOLS:
            if not isinstance(value, bool):
                return None
        else:
            return None
        record[key] = value
    return record


def _owner_only_directory(path: Path) -> None:
    parent = path.parent
    ancestor = parent.parent
    if ancestor.exists() or ancestor.is_symlink():
        ancestor_info = ancestor.lstat()
        if (
            stat.S_ISLNK(ancestor_info.st_mode) or not stat.S_ISDIR(ancestor_info.st_mode)
            or ancestor_info.st_uid != os.geteuid()
        ):
            raise OSError("unsafe diagnostics parent")
    # Only the dedicated final directory may be created; never chmod its parents.
    if parent.exists() or parent.is_symlink():
        info = parent.lstat()
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode) or info.st_uid != os.geteuid() or info.st_mode & 0o077:
            raise OSError("unsafe diagnostics directory")
    else:
        parent.mkdir(mode=0o700)
        info = parent.lstat()
        if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.geteuid():
            raise OSError("unsafe diagnostics directory")

    # Protect existing active and backup files before RotatingFileHandler opens
    # or renames them. A private 0700 directory also fences the rotate sequence.
    for candidate in (path, *(Path(f"{path}.{index}") for index in range(1, BACKUP_COUNT + 1))):
        if candidate.exists() or candidate.is_symlink():
            info = candidate.lstat()
            if (
                stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode)
                or info.st_uid != os.geteuid() or info.st_mode & 0o077
            ):
                raise OSError("unsafe diagnostics file")


class _SafeRotatingHandler(logging.handlers.RotatingFileHandler):
    def __init__(self, filename: str):
        path = Path(filename)
        _owner_only_directory(path)
        super().__init__(filename, maxBytes=MAX_BYTES, backupCount=BACKUP_COUNT, encoding="utf-8", delay=True)
        self.setFormatter(logging.Formatter("%(message)s"))
        self.addFilter(_DiagnosticFilter())
        # Use the same restrictive, no-follow open for the initial file and
        # every active-file reopen after rotation.
        self.stream = self._open()

    def _open(self):
        flags = os.O_CREAT | os.O_APPEND | os.O_WRONLY
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        fd = os.open(self.baseFilename, flags, 0o600)
        try:
            info = os.fstat(fd)
            if not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid() or info.st_mode & 0o077:
                raise OSError("unsafe diagnostics file")
            return os.fdopen(fd, self.mode, encoding=self.encoding, errors=self.errors)
        except Exception:
            os.close(fd)
            raise

    def doRollover(self) -> None:
        _owner_only_directory(Path(self.baseFilename))
        super().doRollover()

    def handleError(self, record: logging.LogRecord) -> None:
        _disable_file_sink()
        _warn_once()


class _DiagnosticFilter(logging.Filter):
    def filter(self, record: logging.LogRecord) -> bool:
        return getattr(record, "deepgram_diagnostic", False) is True


class _StdoutHandler(logging.Handler):
    def emit(self, record: logging.LogRecord) -> None:
        try:
            sys.stdout.write(record.getMessage() + "\n")
            sys.stdout.flush()
        except Exception:
            _warn_once()


def _configure_logger() -> None:
    global _STDOUT_HANDLER
    with _CONFIG_LOCK:
        _LOGGER.setLevel(logging.INFO)
        _LOGGER.propagate = False
        _LOGGER.filters.clear()
        _LOGGER.addFilter(_DiagnosticFilter())
        if _STDOUT_HANDLER not in _LOGGER.handlers:
            handler = _StdoutHandler()
            handler.setLevel(logging.INFO)
            handler.addFilter(_DiagnosticFilter())
            _STDOUT_HANDLER = handler
            _LOGGER.addHandler(handler)


def _warn_once() -> None:
    global _WARNING_EMITTED
    with _WARNING_LOCK:
        if _WARNING_EMITTED:
            return
        _WARNING_EMITTED = True
    # Fixed content only: no path, exception, or log record details.
    try:
        print("deepgram_live_file_log_unavailable", flush=True)
    except Exception:
        pass


def _disable_file_sink() -> None:
    global _FILE_HANDLER, _FILE_PATH
    with _CONFIG_LOCK:
        handler, _FILE_HANDLER = _FILE_HANDLER, None
        _FILE_PATH = None
        if handler is not None:
            _LOGGER.removeHandler(handler)
            try:
                handler.close()
            except Exception:
                pass


def configure_file_sink(path_value: str | None) -> None:
    """Attach an idempotent, best-effort file sink for allowlisted records only."""
    global _FILE_HANDLER, _FILE_PATH
    _configure_logger()
    if not path_value:
        return
    path = os.path.abspath(path_value)
    with _CONFIG_LOCK:
        if _FILE_PATH == path and _FILE_HANDLER in _LOGGER.handlers:
            return
        if _FILE_HANDLER is not None:
            _LOGGER.removeHandler(_FILE_HANDLER)
            try:
                _FILE_HANDLER.close()
            except Exception:
                pass
            _FILE_HANDLER = None
            _FILE_PATH = None
        try:
            handler = _SafeRotatingHandler(path)
        except Exception:
            _warn_once()
            return
        _FILE_HANDLER = handler
        _FILE_PATH = path
        _LOGGER.addHandler(handler)


def emit(event: str, *, diagnostic_id: str | None = None, level: int = logging.INFO, **fields: Any) -> None:
    """Emit a closed-schema record; invalid events/fields are dropped silently."""
    try:
        record = _safe_record(event, diagnostic_id, fields)
        if record is None:
            return
        _LOGGER.setLevel(logging.INFO)
        _LOGGER.log(level, json.dumps(record, sort_keys=True, separators=(",", ":")), extra={"deepgram_diagnostic": True})
    except Exception:
        # Diagnostics must never interrupt an active recording.
        _warn_once()


def reset_for_tests() -> None:
    """Reset module-owned handlers/state for isolated logging tests."""
    global _WARNING_EMITTED
    _disable_file_sink()
    with _WARNING_LOCK:
        _WARNING_EMITTED = False
